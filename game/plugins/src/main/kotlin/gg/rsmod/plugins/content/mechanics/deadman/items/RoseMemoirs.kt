A gift for Rose.

If it pleases you, my dear child, would you record our future outings? When I'm old and my mind is fading I'd like to reminisce all the times we've spent together around this fine Kingdom of mine. Heed the lessons of our time together and reflect, for someday you will be Queen over this great land.

'Lunch by the Lancalliums'
...

Today Father and I had lunch by the River Hos, we sat on our favorite bench and watched as the farmers tended to their curious Bologano fruits. We were joined by a young farmer called Gric, he gave me a basket of strawberries and they're the best I've ever tasted! I recall he was writing a book and he and father discussed the mysteries of ageing for quite some time before he took leave and returned to his farm.

The Lancalliums we'd planted previously were looking a little wilted but Father informed me that Gric would see to them and make sure that they wouldn't die. I asked if Gric could stop anything from dying, Father informed me that in the past a great wizard once beat death and this eventually lead to the residents of Arceuus being immortal, but they had to abandon most of what made them Human to do so. In the end, is it worth it? Forever is a long time and the mind is more fragile than you may realise.

The Fisher's Flute
This happened a few weeks back, I've finally decided to write it down, perhaps it'll help.

A favourite locale of ours is the Fisher's Market at the crossroads in Piscarilius, the merchants are lovely and the music is always enjoyable! The smell may not be for everyone, but after a while you'll forget about it. Being royalty, it's good practise to dress down and be somewhat anonymous as Father believes it's a good lesson in understanding the residents, for both the good traits and the bad. Today was a bad day.

We were stood on the corner, listening to Rey play his golden flute (He always plays my requests and gives us fish when we leave, I'll miss his music.) and just as he had finished playing 'Mist on the River Hos' it happened. It was over quickly, a man stepped from the crowds and attempted to take the golden flute, Father instantly stepped between the two of them when suddenly a woman stepped forward with a knife. Blood was drawn, civilians screamed and the criminals ran.

Father only sustained minor injury but The Fisher's Market is closed now and I believe Rey blames himself for all of it. I'm sure there is a lesson to be learnt from all of this but I'm currently yet to understand it.

History and Hearsay
We left from the southern gate and travelled down the road which passed by the Mess. The usual discord echoed forth, merriment, humour and the clatter of cutlery. The southern door swung listlessly in the wind, further adding to the cacophony with a piercing creak. We turned off towards the west and headed over the stream, up the hill and towards the training grounds. Father slowed the Oxen to a steady pace as we passed by, but it was barren, bar 3 brutish men sparring silently in the combat ring.

As we entered the graveyard, the wind blustered suddenly and I had to grip my coat in spite of the bitter conditions. I approached the grave cautiously, unsure of what I was expecting to happen, but whatever it may have been, it didn't. I quickly placed the Rose down and shuffled off down the path, Father prefers to speak with her by himself.

I approached the old crypt and was surprised to see a strange man perched by the door. Noticing me, he smiled and greeted me, showing me a mouth full of blackened stumps.

'Morning love, what a day, 'ey?' he remarked.

'Foul,' I responded quietly.

'Pah! You know who's buried in this here tomb?' he pondered.

'I was told it's where we would bury our kings and queens, when there was space, anyway.' I spoke more to myself than the man, but he responded nonetheless.

'Aye! But d'you hear of the Wizard?' he asked.

'What Wizard?' I asked, failing to hide my curiosity.

'Been dead for a good while, so they say,' he smirked.

'Well, I've never heard of them,' I admitted.

'Do they no longer teach ye history? A high-born girl like you should be educated,' the man said as he wiped the sweat from his brow. His hands were far dirtier than I'd first noticed.

'Of course they do, I've even read Remoh's 'Tale of Darkness', the original manuscript,' I gloated, regretting instantly as it gave away my position far more than he had already inferred.

'So yer 'ighness knows all about the Catacombs,' his eyes shone with a strange intensity.

'I do, but don't try to scare me with monsters, I know of the powerful magic that keeps them bound below,' I snapped, this conversation would likely displease Father if I continued any further.

'Below?' He laughed 'The entrance may be below the earth, but that realm lies beyond the reach of us mere mortals,'

'But Lustre was just a man and he entered without issue,' I countered.

'Other powers are at work, m'lady, powers far beyond the likes of us,' as he spoke, he eyed the crypt suspiciously, it looked as if he were about to say more when Father suddenly arrived.

'What nonsense are you bothering my child with, digger?' he demanded. The man struggled to his knees, submitting to his King, but his mouth kept that sardonic grin he enjoyed wearing.

'I beg your pardon, your highness! I was unaware of the girls stature,' he grovelled.

'Regardless, you should mind your tongue, spreading hearsay is a crime against the crown,' Father spoke with authority, one must if you expect your subjects to listen.

'Oh, I wouldn't dare stoop so low. It was but a folktale, your highness,' the man explained.

'Hmm, don't you have a job that needs attending?' Father questioned.

'That I do,' he responded while bowing far lower than necessary and he quickly hobbled away.

'What have I said about talking to strangers? Do you forget yourself, child?' Father scolded.

'I'm sorry Father, I wasn't expecting him to be here, I've always enjoyed visiting the old crypt,' I explained.

'Come along now, Rose, let's head back to the cart before the sun sets,'.

Jewellery of Jubilation
During our monthly trip into the Lovakengj districts we made a peculiar stop at a tinkers market stall. I asked father what exactly he had purchased multiple times, but he was unwilling to speak on the matter. Upon our return home, father quickly disappeared to his study and wasn't seen again all day.

At this morning's breakfast he revealed to me what he'd been hiding in the form of a birthday present. It's beautiful! A locket of pale gold shaped like a rose that contains a wonderful painting of mother opposite a dark purple crystal. The gemstone seemed to lack a reflection altogether and it lay eerily bathed in shadow regardless of the light streaming in through the windows. The metalwork showed clear signs of age as well as a recent cleaning; father says he's uncertain of the precise age of the locket. He assured me it's certainly at least several centuries old in between quick sips from a peculiar ornate flask with an 'X' imprinted on the side. I suppose he picked that up yesterday from the tinker as well.

'Much planned for the day, father?' I asked, afraid that he plans to spend yet another day locked away from the world.

'Ah, well... yes, back to the study. In the middle of a book, very illuminating,' he responded.

'What's it called?' I asked.

'Oh, it's too old to have one of those - a name, that is - as the original cover is a faded mess; even the author is a mystery...' he trailed off.

'What's it about?' I knew he had no intention of sharing the details, but I'm nosey.

'You sure have a lot of questions today... It's no story of heroes or lovers' quarrels, so I fear you may find the matter rather dull,'

That was essentially the end of the conversation as he refused to share any more about these mysterious books he's been reading. Father has been acting quite odd lately... I should keep a close eye on him, secrecy doesn't suit him.

The rest of my day was fairly predictable, 'friends' visited me to shower me in gifts - in which I have very little use for - and then there was a feast in the evening. Father managed to show his face for that, although - as expected - he left early.

A Dark Disposition
The sky was gold and the mist rose in eerie swirls as the wind swept through the empty streets of Arceuus. 'A meeting' was all father had said when he left the table at breakfast; the purple bags under his eyes showed that he hadn't slept in days. Recently he's been acting quite odd, secluded in his study for days on end. Recently? He's always been like this I suppose. Still, this time something seems different.

Sneaking out of the castle to follow him was far easier than it should have been, the guards had left their posts and on the journey I saw not a soul. Crouching down behind some magic trees, I could see father waiting by a still pool, he had his pipe and blue smoke made ominous shapes above him in the dim morning light. Suddenly, a hooded figure manifested from the mist and father did something I'll never forget. He knelt.

'You're the priestess?' he choked.

'I am,' the hooded figure responded in a whisper.

'I... I've done everything you've asked,' he kept his eyes down as he spoke.

'I want something else,' she said.

'Yes?'

'Take a drink, you sound thirsty,' she smirked.

Reluctantly, father took his flask from his pocket and took a sip from it. Pain cut across his face and the flask fell from his grip.

'Perfect,' she turned her head and looked directly at me.

Light burst from fathers' eyes and mouth and he slumped to the ground silently. The world around me spun and I awoke screaming in my bed. My locket burned against my chest; was it a dream or is my father truly gone? The doors to my bedroom burst open and my handmaid Alyssa rushed to my side.

'What is it child? An intruder?' she asked.

'No, just a dream... Where's father?' it was clear she wasn't expecting me to ask that.

'...Why, he left the castle as soon as he finished his breakfast,' she explained

'What happened? A nightmare?'

'You could say that,' I rushed to my desk and began filling in this entry. I fear everything is about to change.

Tread Carefully
If you're reading this, things haven't gone to plan and YOU should be worried. The King has been killed and I am 'Unfit for rule'... I have enough sanity left to know it won't be long until they come for me too.

By all means, young stranger, attempt to rebuild this memoir, but I'm afraid you may not like the ending, I for one am not a fan. You may think you're ahead of the game, but the pieces have been in motion for decades and you are just another pawn, as was I.

Perhaps we'll meet soon.

R,
