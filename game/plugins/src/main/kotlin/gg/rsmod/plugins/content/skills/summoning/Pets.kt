/**
 * The 71 OSRS pets as followers, the same way a Summoning familiar follows (owner 2026-09-30: "import all osrs pets from osrs and make
 * them fully functioning just like summoning").
 *
 * Data: `data/cfg/pets/pets.tsv` (generated by `OsrsPetImportTool table`: every variant's local item and follower npc) and
 * `data/cfg/pets/pet_tiers.tsv` (tier, and the boss npcs that roll the pet on a kill).
 *
 * Rules and their sources:
 * - One follower at a time, familiar or pet. Dropping the pet item spawns the follower with the drop animation 827, and with a follower
 *   already out the item stays: "You already have a follower." (Novite rev-667 `PetManager.spawnPet`).
 * - Pick-up puts the pet back as its item (animation 827); another player's pet: "This isn't your pet." (Novite `NPCHandler`).
 * - The Summoning tab (662) and orb (747) show the pet like a familiar: varp 448 = the pet's item, varp 1174 = its npc (Novite
 *   `Pet.sendMainConfigurations` / `switchOrb`), with Call Follower and Dismiss. Following, the recovery teleport and the placement beside
 *   the owner are [Familiar]'s own code. Dismiss returns the pet to the inventory (or the bank): an OSRS pet cannot be freed.
 * - The pet survives logout and death ("Pets will now respawn with you on death and will keep on following you", OSRS Wiki Pet).
 * - Metamorphosis turns the pet into the next variant of the same pet (OSRS Wiki Metamorphosis). CUSTOM_SERVER_OVERRIDE: the OSRS
 *   unlock items (metamorphic dust, remnants, ores, ...) do not exist here, so every variant of the pet is in the cycle.
 * - A boss kill rolls its pet at the OSRS rate times the killer's Annihilation drop rate (N313) (OSRS Wiki Pet): "You have a funny feeling like you're being followed." (follower),
 *   "You feel something weird sneaking into your backpack." (a follower is already out), "You have a funny feeling like you would have
 *   been followed..." (already owned). With no room at all OSRS sends the pet to Probita; there is no Probita here, so it goes to the bank
 *   (CUSTOM_SERVER_OVERRIDE).
 */
object Pets {
    const val TABLE_PATH = "./data/cfg/pets/pets.tsv"
    const val TIERS_PATH = "./data/cfg/pets/pet_tiers.tsv"

    /**
     * N216 (owner 2026-10-23: a baby dragon or terrier from the store dropped on the floor instead of following): the 667 pets - the
     * cats, dogs, baby dragons and every other Summoning-era pet item - follow like the OSRS pets. One pet per item (no growth or
     * hunger); item -> follower npc from the donors' pet tables, each pair checked against this cache ([parseClassicTable]).
     */
    const val CLASSIC_TABLE_PATH = "./data/cfg/pets/pets_667.tsv"

    /**
     * N423: base follower npc -> its "Upgraded <name>" copy (BurdenTrinketTool npcs): same models, head, animations and size, a
     * Store op. A pet with a bound burden trinket follows as the copy; everything that knows a pet by npc id sees the copy as
     * the same pet ([variantOfNpc], [baseNpc]).
     */
    const val UPGRADES_TABLE_PATH = "./data/cfg/pets/pet_upgrades.tsv"

    /** Novite rev-667 `PetManager.spawnPet` / `NPCHandler` pet pick-up. */
    const val DROP_ANIMATION = 827

    /**
     * The engine's own cues for putting an item down and taking one (IfButton1Handler drop: synth 2739 "put_down";
     * GroundItemPathAction take: synth 2582). Dropping a pet item and picking the pet up are those same two acts, but go
     * through [drop] / [pickUp] instead of the engine, which is why they were silent (owner 2026-09-30).
     */
    const val DROP_SOUND = 2739
    const val PICK_UP_SOUND = 2582

    /** Pet cues play at full volume as before (owner-tested 2026-09-30); [sound] also reaches players near the pet. */
    private const val PET_SOUND_VOLUME = 255

    /**
     * Overnight 2026-10-02 block 7 (owner: "pets have no sound at all"): every pet act is heard by the owner AND the players
     * near the pet (they only reached the owner), from the pet's tile.
     */
    private fun sound(player: Player, id: Int, at: gg.rsmod.game.model.Tile? = null) =
        FamiliarAudio.play(player, id, volume = PET_SOUND_VOLUME, at = at)


    /** The OSRS "Getting pet" sound (see [award]). */
    const val GETTING_PET_SOUND = gg.rsmod.plugins.api.cfg.Sfx.TRIFFID_APPEAR

    const val MSG_FOLLOWED = "<col=ef1020>You have a funny feeling like you're being followed.</col>"
    const val MSG_BACKPACK = "<col=ef1020>You feel something weird sneaking into your backpack.</col>"
    const val MSG_DUPLICATE = "<col=ef1020>You have a funny feeling like you would have been followed...</col>"
    const val MSG_BANKED = "<col=ef1020>You have a funny feeling like you're being followed... your pet has been sent to your bank.</col>"

    /** N414: no room in the backpack or the bank - Perdu keeps the pet (OSRS: Probita), free to collect. */
    const val MSG_TO_PERDU = "<col=ef1020>You have a funny feeling like you're being followed... you had no room, so Perdu at the Grand Exchange is looking after your pet.</col>"

    /** OSRS Wiki Pet: "Pets are limited to walking pace, except Nexling, Babi (Tumeken's Guardian), and Dogs, which move faster". */
    val FAST_PETS = setOf("Nexling", "Babi")

    /** The two orb / panel actions a pet answers. */
    val ORB_ACTIONS = setOf(FamiliarAction.CALL, FamiliarAction.DISMISS)

    /**
     * N423 (design v6): an upgraded pet's orb is a beast of burden's - Call Follower, Take BoB, Pick-up, Follower Details (the
     * client lists them in its own order); a plain pet keeps Call and Pick-up.
     */
    val UPGRADED_ORB_ACTIONS = ORB_ACTIONS + setOf(FamiliarAction.TAKE_BOB, FamiliarAction.FOLLOWER_DETAILS)

    /** The orb / left-click actions [player]'s pet answers right now. */
    fun orbActions(player: Player): Set<FamiliarAction> = if (BeastOfBurden.isUpgradedPetOut(player)) UPGRADED_ORB_ACTIONS else ORB_ACTIONS

    data class Variant(
        val pet: String,
        val name: String,
        val item: Int,
        val npc: Int,
        /** The OSRS item id of the variant ([PetMorphs] keys its unlock rules on it); -1 in hand-built tables. */
        val osrsItem: Int = -1,
        /** A 667 pet ([CLASSIC_TABLE_PATH]): no tier, no OSRS item. */
        val classic: Boolean = false,
    )

    data class PetInfo(
        val pet: String,
        val tier: Int,
        val dropNpcs: Set<Int>,
        val dropRate: Int,
    ) {
        val dropOnly: Boolean get() = dropNpcs.isNotEmpty()
    }

    @Volatile
    var variants: List<Variant> = emptyList()
        private set

    @Volatile
    var infos: Map<String, PetInfo> = emptyMap()
        private set

    @Volatile
    private var byItem: Map<Int, Variant> = emptyMap()

    @Volatile
    private var byNpc: Map<Int, Variant> = emptyMap()

    @Volatile
    private var byPet: Map<String, List<Variant>> = emptyMap()

    @Volatile
    private var dropsByNpc: Map<Int, PetInfo> = emptyMap()

    @Volatile
    private var upgradedOf: Map<Int, Int> = emptyMap()

    @Volatile
    private var baseOf: Map<Int, Int> = emptyMap()

    /** `base<TAB>upgraded[<TAB>name]` rows of [UPGRADES_TABLE_PATH]. */
    fun parseUpgrades(lines: List<String>): Map<Int, Int> =
        lines.filter { it.isNotBlank() && !it.startsWith("#") }.associate { line ->
            val c = line.split('\t')
            c[0].trim().toInt() to c[1].trim().toInt()
        }

    fun installUpgrades(table: Map<Int, Int>) {
        upgradedOf = table
        baseOf = table.entries.associate { it.value to it.key }
    }

    /** The plain follower npc behind [npc] (itself for a plain pet or any other npc). */
    fun baseNpc(npc: Int): Int = baseOf[npc] ?: npc

    /** The "Upgraded" copy of follower [npc], or null when the table has none. */
    fun upgradedNpc(npc: Int): Int? = upgradedOf[npc]

    fun isUpgradedNpc(npc: Int): Boolean = npc in baseOf

    /** Every Upgraded copy (option bindings). */
    val upgradedNpcs: Collection<Int> get() = baseOf.keys

    /** The npc [variant] follows [player] as: its Upgraded copy while a burden trinket is bound to the pet. */
    fun followerNpc(
        player: Player,
        variant: Variant,
    ): Int = if (BurdenTrinkets.upgradeOf(player, variant.pet) != null) upgradedOf[variant.npc] ?: variant.npc else variant.npc

    @Volatile
    private var upgradedItemOf: Map<Int, Int> = emptyMap()

    @Volatile
    private var baseItemOf: Map<Int, Int> = emptyMap()

    /** N436: base pet item -> its "Upgraded" item copy (data/cfg/pets/pet_item_upgrades.tsv, same row shape as the npc table). */
    const val ITEM_UPGRADES_TABLE_PATH = "./data/cfg/pets/pet_item_upgrades.tsv"

    fun installItemUpgrades(table: Map<Int, Int>) {
        upgradedItemOf = table
        baseItemOf = table.entries.associate { it.value to it.key }
    }

    /** The plain pet item behind [item] (itself for a plain pet item or any other item). */
    fun baseItemOf(item: Int): Int = baseItemOf[item] ?: item

    fun isUpgradedItem(item: Int): Boolean = item in baseItemOf

    /** Every Upgraded item copy (option bindings). */
    val upgradedItems: Collection<Int> get() = baseItemOf.keys

    /**
     * N436 (owner 2026-10-30: an upgraded pet "moet dat ook zo laten zien in de inventory"): the item [variant] is held as - its
     * "Upgraded" copy while a burden trinket is bound to the pet, else the plain item.
     */
    fun shownItem(
        player: Player,
        variant: Variant,
    ): Int = if (BurdenTrinkets.upgradeOf(player, variant.pet) != null) upgradedItemOf[variant.item] ?: variant.item else variant.item

    /**
     * N436: every pet item in the inventory and the bank turned into the version its binding asks for (after a Bind or Unbind - the
     * pet may be in the bank - and at login). The swap keeps the slot; nothing is added or lost.
     */
    fun reconcileItems(player: Player) {
        listOf(player.inventory, player.bank).forEach { container ->
            for (slot in 0 until container.capacity) {
                val item = container[slot] ?: continue
                val variant = variantOfItem(item.id) ?: continue
                val want = shownItem(player, variant)
                if (want != item.id) container[slot] = Item(want, item.amount)
            }
        }
    }

    /** The live follower npc; transient like [FAMILIAR_ATTR]. */
    val PET_ATTR = AttributeKey<WeakReference<Npc>>()

    /** The item of the pet that is out, persisted so the pet comes back on login. */
    val PET_ITEM_ATTR = AttributeKey<Int>(persistenceKey = "osrs_pet_item")

    fun parseTable(lines: List<String>): List<Variant> =
        lines.filter { it.isNotBlank() && !it.startsWith("#") }.map { line ->
            val c = line.split('\t')
            require(c.size >= 4) { "bad pet table line '$line'" }
            Variant(c[0], c[1], c[2].trim().toInt(), c[3].trim().toInt(), c.getOrNull(4)?.trim()?.toIntOrNull() ?: -1)
        }

    /** `name<TAB>item<TAB>npc` rows of [CLASSIC_TABLE_PATH]: each item is its own pet, named "name (item)". */
    fun parseClassicTable(lines: List<String>): List<Variant> =
        lines.filter { it.isNotBlank() && !it.startsWith("#") }.map { line ->
            val c = line.split('\t')
            require(c.size >= 3) { "bad 667 pet line '$line'" }
            val item = c[1].trim().toInt()
            Variant("${c[0]} ($item)", c[0], item, c[2].trim().toInt(), classic = true)
        }

    fun parseTiers(lines: List<String>): List<PetInfo> =
        lines.filter { it.isNotBlank() && !it.startsWith("#") }.map { line ->
            val c = line.split('\t')
            require(c.size >= 2) { "bad pet tier line '$line'" }
            val npcs = c.getOrNull(2)?.split(',')?.mapNotNull { it.trim().toIntOrNull() }?.toSet() ?: emptySet()
            val rate = c.getOrNull(3)?.trim()?.toIntOrNull() ?: 0
            require(c[1].trim().toInt() in 1..3) { "pet '${c[0]}' tier must be 1..3" }
            require(npcs.isEmpty() == (rate == 0)) { "pet '${c[0]}' needs both drop npcs and a drop rate, or neither" }
            PetInfo(c[0], c[1].trim().toInt(), npcs, rate)
        }

    fun install(
        table: List<Variant>,
        tiers: List<PetInfo>,
    ) {
        variants = table
        byItem = table.associateBy { it.item }
        byNpc = table.associateBy { it.npc }
        byPet = table.groupBy { it.pet }
        infos = tiers.associateBy { it.pet }
        dropsByNpc = tiers.flatMap { info -> info.dropNpcs.map { it to info } }.toMap()
    }

    /** Loads the OSRS table, its tiers and the 667 pets; returns the variant count (0 when the OSRS table has not been generated yet). */
    fun load(
        table: File = File(TABLE_PATH),
        tiers: File = File(TIERS_PATH),
        classic: File = File(CLASSIC_TABLE_PATH),
    ): Int {
        if (!table.exists()) return 0
        val osrs = parseTable(table.readLines())
        val osrsItems = osrs.map { it.item }.toSet()
        val osrsNpcs = osrs.map { it.npc }.toSet()
        // An item or npc both tables name stays the OSRS pet's.
        val old = if (classic.exists()) parseClassicTable(classic.readLines()).filter { it.item !in osrsItems && it.npc !in osrsNpcs } else emptyList()
        install(osrs + old, if (tiers.exists()) parseTiers(tiers.readLines()) else emptyList())
        val upgrades = File(table.parentFile, File(UPGRADES_TABLE_PATH).name)
        installUpgrades(if (upgrades.exists()) parseUpgrades(upgrades.readLines()) else emptyMap())
        val itemUpgrades = File(table.parentFile, File(ITEM_UPGRADES_TABLE_PATH).name)
        installItemUpgrades(if (itemUpgrades.exists()) parseUpgrades(itemUpgrades.readLines()) else emptyMap())
        return variants.size
    }

    fun isPetItem(item: Int): Boolean = item in byItem || item in baseItemOf

    fun isPetNpc(npc: Int): Boolean = npc in byNpc || npc in baseOf

    fun variantOfItem(item: Int): Variant? = byItem[item] ?: baseItemOf[item]?.let { byItem[it] }

    fun variantOfNpc(npc: Int): Variant? = byNpc[npc] ?: baseOf[npc]?.let { byNpc[it] }

    fun variantsOf(pet: String): List<Variant> = byPet[pet] ?: emptyList()

    /** The pet's first variant: the one a boss drops and a shop sells. */
    fun baseItem(pet: String): Int? = byPet[pet]?.firstOrNull()?.item

    fun dropFor(npcId: Int): PetInfo? = dropsByNpc[npcId]

    /** The variant after [item] in its pet's variant cycle (itself for a single-variant pet). */
    fun nextVariant(item: Int): Variant? {
        val v = variantOfItem(item) ?: return null
        val all = byPet.getValue(v.pet)
        return all[(all.indexOf(v) + 1) % all.size]
    }

    fun current(player: Player): Npc? {
        val npc = player.attr[PET_ATTR]?.get() ?: return null
        if (!player.world.npcs.contains(npc)) {
            player.attr.remove(PET_ATTR)
            return null
        }
        return npc
    }

    fun itemOf(player: Player): Int? = player.attr[PET_ITEM_ATTR]

    fun hasFollower(player: Player): Boolean = Familiar.current(player) != null || current(player) != null

    private fun spawn(
        player: Player,
        variant: Variant,
        tile: gg.rsmod.game.model.Tile = Familiar.placementTile(player, variant.npc),
    ): Npc {
        val npc = Npc(player, followerNpc(player, variant), tile, player.world)
        npc.publicOwner = true
        // Followers walk in their owner's footsteps; other creatures must not stop them dead (same as a familiar).
        npc.ignoresEntityCollision = true
        npc.respawnOverride = false
        player.world.spawn(npc)
        npc.facePawn(player)
        player.attr[PET_ATTR] = WeakReference(npc)
        player.attr[PET_ITEM_ATTR] = variant.item
        Familiar.updateHud(player)
        gg.rsmod.game.model.Trace.log(gg.rsmod.game.model.Trace.Cat.SUMMON) { "pet ${variant.name} npc ${npc.id}#${npc.index} out for ${player.username}" }
        return npc
    }

    private fun clear(player: Player) {
        // N423: an upgraded pet's Store window goes with the pet (as a familiar's does on dismiss).
        FamiliarInventory.close(player)
        current(player)?.let { player.world.remove(it) }
        player.attr.remove(PET_ATTR)
        player.attr.remove(PET_ITEM_ATTR)
        Familiar.updateHud(player)
    }

    /** Drop on a pet item: the follower comes out. Returns true when the item was used (the engine must then not drop it). */
    fun drop(
        player: Player,
        item: Int,
        slot: Int,
    ): Boolean {
        val variant = variantOfItem(item) ?: return false
        if (hasFollower(player)) {
            player.message("You already have a follower.")
            return true
        }
        val removed = player.inventory.remove(item, 1, assureFullRemoval = true, beginSlot = slot.coerceAtLeast(0))
        if (!removed.hasSucceeded()) {
            gg.rsmod.game.model.Trace.problem(gg.rsmod.game.model.Trace.Cat.SUMMON) { "pet drop: item $item not in ${player.username}'s slot $slot" }
            return true
        }
        player.animate(DROP_ANIMATION)
        val npc = spawn(player, variant)
        sound(player, DROP_SOUND, npc.tile)
        PetVoices.appear(player, npc)
        return true
    }

    /**
     * N423: an upgraded pet carrying items is picked up like a beast of burden is dismissed - asked first, then its pack goes to
     * Death's Office (normal fee). Returns true when the caller may go on now (nothing carried); false when a question was asked
     * and [then] runs on "Yes".
     */
    private fun confirmCargo(
        player: Player,
        then: () -> Unit,
    ): Boolean {
        if (!BeastOfBurden.isUpgradedPetOut(player) || BeastOfBurden.storedCount(player) == 0) return true
        player.queue {
            // The title line holds about 40 characters between its two swords; the consequence goes into the answer.
            if (options("Yes - its items go to Death's Office.", "No.", title = "Your pet is carrying items. Pick it up?") == 1) then()
        }
        return false
    }

    /** Pick-up on the follower: back into the inventory. */
    fun pickUp(
        player: Player,
        npc: Npc,
        confirmed: Boolean = false,
    ) {
        if (current(player) !== npc) {
            player.message("This isn't your pet.")
            return
        }
        // N436: back into the backpack as the version its binding asks for ("Upgraded <name>" while a trinket is bound).
        val item = (itemOf(player) ?: variantOfNpc(npc.id)?.item)?.let { i -> variantOfItem(i)?.let { shownItem(player, it) } ?: i } ?: return
        if (!player.inventory.hasSpace) {
            player.message("You don't have enough inventory space to do that.")
            return
        }
        if (!confirmed && !confirmCargo(player) { pickUp(player, npc, confirmed = true) }) return
        BeastOfBurden.release(player)
        player.animate(DROP_ANIMATION)
        val at = npc.tile
        clear(player)
        player.inventory.add(item, 1, assureFullInsertion = true)
        sound(player, PICK_UP_SOUND, at)
    }

    /** Dismiss from the Summoning tab / orb: the pet goes to the inventory, else the bank; it is never lost. */
    fun dismiss(
        player: Player,
        confirmed: Boolean = false,
    ) {
        current(player) ?: return
        val item = itemOf(player)?.let { i -> variantOfItem(i)?.let { shownItem(player, it) } ?: i } ?: return
        if (!confirmed && !confirmCargo(player) { dismiss(player, confirmed = true) }) return
        if (player.inventory.hasSpace || player.bank.hasSpace) BeastOfBurden.release(player)
        when {
            player.inventory.hasSpace -> {
                val at = current(player)?.tile
                clear(player)
                player.inventory.add(item, 1, assureFullInsertion = true)
                sound(player, PICK_UP_SOUND, at)
                player.message("Your pet is now in your backpack.")
            }
            player.bank.add(item, 1, assureFullInsertion = true).hasSucceeded() -> {
                val at = current(player)?.tile
                clear(player)
                sound(player, PICK_UP_SOUND, at)
                player.message("Your pet has been sent to your bank.")
            }
            else -> player.message("You don't have enough inventory or bank space to do that.")
        }
    }

    /** "Call Follower": the pet is placed beside its owner. */
    fun call(player: Player): Boolean {
        val npc = current(player) ?: return false
        npc.teleportNpc(Familiar.placementTile(player, npc.id))
        Familiar.playFollowerCall(player, npc)
        npc.facePawn(player)
        PetVoices.appear(player, npc)
        return true
    }

    /** Metamorphosis on the follower: the next variant of the pet, in place. */
    fun metamorph(
        player: Player,
        npc: Npc,
    ) {
        if (current(player) !== npc) {
            player.message("This isn't your pet.")
            return
        }
        val next = PetMorphs.nextUnlocked(player, itemOf(player) ?: return) ?: return
        if (next.npc == baseNpc(npc.id)) return
        morphFollower(player, next)
    }

    /** The follower becomes [variant] where it stands (Metamorphosis, an unlock item, a rift guardian's altar). */
    fun morphFollower(
        player: Player,
        variant: Variant,
    ) {
        val npc = current(player) ?: return
        if (npc.id == followerNpc(player, variant)) return
        val tile = npc.tile
        player.world.remove(npc)
        spawn(player, variant, tile)
        // No sound: OSRS documents none for Metamorphosis (wiki "Metamorphosis", re-checked 2026-10-05). The summoning-arrival cue
        // that played here was invented (owner 032316: "a lot of pets still do have sounds").
    }

    /**
     * N423: after a burden trinket is bound or unbound, the follower turns into its Upgraded copy or back where it stands - the
     * same respawn as [morphFollower]; the item, the variant and the pack stay.
     */
    fun refreshUpgrade(player: Player) {
        val item = itemOf(player) ?: return
        val variant = variantOfItem(item) ?: return
        morphFollower(player, variant)
    }

    /** Metamorphosis on the pet item (the OSRS items that carry it as an inventory option). */
    fun metamorphItem(
        player: Player,
        item: Int,
        slot: Int,
    ) {
        val next = PetMorphs.nextUnlocked(player, item) ?: return
        if (next.item == item) return
        val current = player.inventory[slot]
        if (current?.id != item) return
        player.inventory[slot] = Item(shownItem(player, next), 1)
    }

    /**
     * Whether [player] already has [pet] (any variant) anywhere - following, in any container (inventory, bank, a
     * familiar's pack, gravestone, Death's Office) or on the Grand Exchange: OSRS's duplicate rule (K01 deel 3, the shared
     * [gg.rsmod.plugins.content.mechanics.ownership.Possessions] check; before, only the follower, inventory and bank counted).
     */
    fun owns(
        player: Player,
        pet: String,
    ): Boolean =
        gg.rsmod.plugins.content.mechanics.ownership.Possessions.owns(
            player,
            variantsOf(pet).flatMap { listOfNotNull(it.item, upgradedItemOf[it.item]) }.toSet(),
        )

    /** The pets [player] has ever had, as their [baseItem]s (N414: Perdu gives a lost pet back for free, one of each pet). */
    val OWNED_ATTR = AttributeKey<String>(persistenceKey = "pets_owned")

    fun ownedOnce(player: Player): Set<String> =
        player.attr[OWNED_ATTR].orEmpty().split(',').mapNotNull { it.trim().toIntOrNull()?.let { item -> variantOfItem(item)?.pet } }.toSet()

    private fun recordOwned(
        player: Player,
        pets: Collection<String>,
    ) {
        val items = player.attr[OWNED_ATTR].orEmpty().split(',').mapNotNull { it.trim().toIntOrNull() }.toMutableSet()
        val before = items.size
        pets.mapNotNullTo(items) { baseItem(it) }
        if (items.size != before) player.attr[OWNED_ATTR] = items.sorted().joinToString(",")
    }

    /**
     * Records every pet [player] has now - following, in any container - and every pet in their Collection Log as owned once, so
     * a pet lost before this record existed can be given back too. Run at login and when Perdu is asked.
     */
    fun observe(player: Player) {
        val seen = mutableSetOf<String>()
        itemOf(player)?.let { variantOfItem(it)?.pet }?.let { seen += it }
        player.containers.values.forEach { container ->
            container.rawItems.forEach { item -> item?.let { variantOfItem(it.id)?.pet }?.let { seen += it } }
        }
        byItem.forEach { (item, variant) ->
            if (variant.pet !in seen && runCatching { gg.rsmod.plugins.content.quests.tab.CollectionLog.has(player, item) }.getOrDefault(false)) seen += variant.pet
        }
        recordOwned(player, seen)
    }

    /** N414: the pets [player] had once and has nowhere now - Perdu gives each back for free. */
    fun lost(player: Player): List<String> = ownedOnce(player).filter { !owns(player, it) }.sortedBy { baseItem(it) }

    enum class Award { DUPLICATE, FOLLOWER, BACKPACK, BANK, LOST }

    /** Where a pet reward goes (OSRS Wiki Pet, "Obtaining a pet"; the bank replaces Probita here). */
    fun awardOutcome(
        alreadyOwned: Boolean,
        followerOut: Boolean,
        inventorySpace: Boolean,
        bankSpace: Boolean,
    ): Award =
        when {
            alreadyOwned -> Award.DUPLICATE
            !followerOut -> Award.FOLLOWER
            inventorySpace -> Award.BACKPACK
            bankSpace -> Award.BANK
            else -> Award.LOST
        }

    /**
     * A pet reward - a boss roll, a skilling pet, the Deadman's chest, a breach monster, a store purchase (N243, owner 2026-10-23: every
     * way a pet arrives gives the OSRS message and the "Getting pet" sound): OSRS's follower / backpack / duplicate rules. A
     * [purchased] pet is never a duplicate (the player paid for this one); returns where it went.
     */
    fun award(
        player: Player,
        pet: String,
        item: Int = baseItem(pet) ?: -1,
        purchased: Boolean = false,
        /** N104: the Drop Viewer entry the pet came from (its kill count goes into the Collection Log); null for skilling. */
        source: String? = null,
    ): Award? {
        if (item < 0 || variantOfItem(item)?.pet != pet) return null
        gg.rsmod.game.model.Trace.log(gg.rsmod.game.model.Trace.Cat.ITEM) { "pet roll hit: $pet for ${player.username}" }
        val outcome = awardOutcome(!purchased && owns(player, pet), hasFollower(player), player.inventory.hasSpace, player.bank.hasSpace)
        // The variant received counts as unlocked (a rift guardian in its altar's colour); a duplicate gives nothing (OSRS Wiki Pet).
        // N414: a pet with no room anywhere is owned all the same - Perdu gives it back for free (OSRS: it goes to Probita).
        if (outcome == Award.LOST) recordOwned(player, listOf(pet))
        if (outcome != Award.DUPLICATE && outcome != Award.LOST) {
            PetMorphs.unlock(player, byItem.getValue(item))
            recordOwned(player, listOf(pet))
            if (!purchased) {
                runCatching { gg.rsmod.plugins.content.quests.tab.CollectionLog.record(player, source, listOf(item to 1)) }
                    .onFailure { gg.rsmod.game.model.Trace.crash("collection log pet", it) }
            }
            // N88 part 1 (Council N88): OSRS plays "Getting pet" on a new pet - Jagex synth 2320 triffid_appear, proven by waveform
            // match against the wiki's Getting_pet.ogg (dossier N88, correlation 0.997) and byte-identical in OSRS and both 667 caches.
            player.playSound(GETTING_PET_SOUND)
        }
        when (outcome) {
            Award.DUPLICATE -> player.message(MSG_DUPLICATE)
            Award.FOLLOWER -> {
                spawn(player, byItem.getValue(item))
                player.message(MSG_FOLLOWED)
            }
            Award.BACKPACK -> {
                player.inventory.add(item, 1, assureFullInsertion = true)
                player.message(MSG_BACKPACK)
            }
            Award.BANK -> {
                player.bank.add(item, 1, assureFullInsertion = true)
                player.message(MSG_BANKED)
            }
            Award.LOST -> {
                player.message(MSG_TO_PERDU)
                gg.rsmod.game.model.Trace.problem(gg.rsmod.game.model.Trace.Cat.ITEM) { "pet $pet for ${player.username}: inventory and bank full, kept by Perdu" }
            }
        }
        return outcome
    }

    /** [award] for whichever pet [item] is (a dropped or bought pet item); null when [item] is no pet. */
    fun awardItem(
        player: Player,
        item: Int,
        purchased: Boolean = false,
    ): Award? = variantOfItem(item)?.let { award(player, it.pet, item, purchased) }

    /**
     * The kill roll's chance per kill of [npcId]: the OSRS 1 / [PetInfo.dropRate] times the killer's Annihilation drop rate [rate]
     * (N313, owner 2026-10-24: "de bracket-boost geldt voor pets" - Pet Zilyana 1/5,000 becomes 1/1,000 at 5x), at most 1; 0 for an
     * npc without a pet. [roll] and the Drop Viewer (N108: Normal = 1x, Your chance = the player's rate) both read it.
     */
    fun dropChance(
        npcId: Int,
        rate: Double = 1.0,
    ): Double = dropFor(npcId)?.let { (rate.coerceAtLeast(1.0) / it.dropRate).coerceAtMost(1.0) } ?: 0.0

    /** The kill roll of `on_npc_killed`: [dropChance] at the killer's kill rate per kill of one of the pet's boss npcs. */
    fun roll(
        player: Player,
        npcId: Int,
    ) {
        val info = dropFor(npcId) ?: return
        val rate = gg.rsmod.plugins.content.drops.DropTableFactory.killRate(player)
        if (player.world.randomDouble() < dropChance(npcId, rate)) award(player, info.pet, source = gg.rsmod.plugins.content.quests.tab.DropSources.forNpc(player, npcId)?.key)
    }

    /** Farther than this from its owner (or on another plane) the pet was left behind by a teleport, not by running. */
    const val TELEPORT_DISTANCE = 30

    /** Once per cycle (familiar tick): follow like a familiar, without a familiar's arrival effect on a recovery teleport. */
    fun tick(player: Player) {
        val npc = current(player) ?: return
        // A pet brought along after its owner TELEPORTED is heard arriving (N298) - not on the catch-up a walking pet gets every
        // dozen tiles behind a running owner, which would make it sound every few seconds.
        val teleported = npc.tile.height != player.tile.height || !npc.tile.isWithinRadius(player.tile, TELEPORT_DISTANCE)
        Familiar.follow(player, npc, recovered = { p, n ->
            n.facePawn(p)
            if (teleported) PetVoices.appear(p, n)
        }, runs = variantOfNpc(npc.id)?.name in FAST_PETS)
        Familiar.updateHud(player)
        PetVoices.idle(player, npc)
        PetVoices.step(player, npc)
    }

    /** Logout: the npc goes, the pet item stays recorded for [restoreOnLogin]. */
    fun disconnect(player: Player) {
        current(player)?.let { player.world.remove(it) }
        player.attr.remove(PET_ATTR)
    }

    fun restoreOnLogin(player: Player) {
        val item = itemOf(player) ?: return
        val variant = variantOfItem(item)
        if (variant == null) {
            // A pet the table no longer knows: give the item back rather than lose it.
            player.attr.remove(PET_ITEM_ATTR)
            if (!player.inventory.add(item, 1, assureFullInsertion = true).hasSucceeded()) player.bank.add(item, 1, assureFullInsertion = true)
            return
        }
        if (Familiar.current(player) != null) {
            // Two followers can never be out together: the pet goes back into the backpack (bank when full).
            player.attr.remove(PET_ITEM_ATTR)
            if (!player.inventory.add(item, 1, assureFullInsertion = true).hasSucceeded()) player.bank.add(item, 1, assureFullInsertion = true)
            return
        }
        PetVoices.appear(player, spawn(player, variant))
    }
