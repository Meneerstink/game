    fun soundFor(item: Int, name: String, slot: EquipmentType): Int {
        val n = name.lowercase()
        val metal = item in METAL
        var sound =
            when (slot) {
                EquipmentType.WEAPON ->
                    when {
                        n.contains("mystic") && n.contains("staff") -> 2230
                        n.contains("spear") || n.contains("staff") || n.contains("javelin") || n.contains("hasta") || n.contains("halberd") -> 2247
                        n.contains("hammer") || n.contains("maul") -> 2243
                        n.contains("mace") || n.contains("flail") -> 2246
                        n.contains("bow") || n.contains("knife") || n.contains("dart") || n.contains("thrownaxe") -> 2244
                        n.contains("whip") -> 2249
                        n.contains("hatchet") -> 2229
                        n.contains("axe") -> 2232
                        n.contains("salamander") -> 732
                        n.contains("banner") -> 2231
                        n.contains("blunt") -> 2233
                        n.contains("ghost buster 500") -> 3228
                        n == "sled" -> 1864
                        n == "dark bow" -> 3738
                        n == "silverlight" -> 2990
                        else -> if (metal) 2248 else CLOTHES
                    }
                EquipmentType.HEAD -> if (n == "jack lantern mask") 3227 else if (metal) 2240 else CLOTHES
                EquipmentType.CHEST -> if (metal) 2239 else CLOTHES
                EquipmentType.SHIELD -> if (metal) 2245 else CLOTHES
                EquipmentType.LEGS -> if (metal) 2242 else CLOTHES
                EquipmentType.BOOTS -> if (metal) 2237 else CLOTHES
                EquipmentType.GLOVES -> if (metal) 2236 else CLOTHES
                EquipmentType.AMMO -> if (metal) 2235 else 2244
                EquipmentType.RING -> if (n == "beacon ring") 3525 else CLOTHES
                else -> CLOTHES
            }
        if (n.contains("jester")) sound = 3395
        if (item in LEATHER) sound = 2241
        if (item in WOOD) sound = 2250
        return sound
    }

    private const val CLOTHES = Sfx.EQUIP_FUN

    fun play(player: Player, item: Int, slot: EquipmentType) {
        val name = player.world.definitions.get(gg.rsmod.game.fs.def.ItemDef::class.java, item).name
        player.playSound(soundFor(item, name, slot))
    }
