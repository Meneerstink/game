package gg.rsmod.plugins.content.mechanics.death

import com.displee.cache.CacheLibrary
import gg.rsmod.game.fs.DefinitionSet
import gg.rsmod.game.fs.def.ItemDef
import gg.rsmod.game.model.item.Item
import gg.rsmod.plugins.api.cfg.Items
import gg.rsmod.plugins.content.mechanics.trouver.TrouverLockables
import gg.rsmod.plugins.content.mechanics.trouver.TrouverRegistry
import java.io.File
import java.nio.file.Paths
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Owner 2026-10-04 ("you need to audit every osrs item and item we have for these mechanics"): every untradeable item of this
 * server (tradeable flag from data/cfg/items.yml, as ItemMetadataService loads it) and every item with a PvP death conversion,
 * run through the real death rules, written to docs/death-item-audit.md. Owner rules:
 *  - you lose everything; Protect Item keeps 1;
 *  - a lockable untradeable (OSRS "(l)" list + this server's lockables) is kept - broken at <= 20, mangled above 20 when locked,
 *    lost above 20 when not locked; killed by a monster it is always kept (and stays locked);
 *  - every other untradeable (Barrows gloves ...) is always lost; the killer receives coins for it.
 */
class DeathItemAuditTests {
    @Test
    fun `every untradeable follows the owner's death rules`() {
        val defs = DefinitionSet()
        defs.loadAll(CacheLibrary(Paths.get("..", "..", "data", "cache").toFile().toString()))
        val tradeable = HashMap<Int, Boolean>()
        val names = HashMap<Int, String>()
        var id = -1
        File("../../data/cfg/items.yml").forEachLine { line ->
            when {
                line.startsWith("- id: ") -> id = line.removePrefix("- id: ").trim().toInt()
                line.startsWith("  name: ") && id >= 0 -> names[id] = line.removePrefix("  name: ").trim().trim('"')
                line.startsWith("  tradeable: ") && id >= 0 -> tradeable[id] = line.endsWith("true")
            }
        }
        tradeable.forEach { (i, t) -> defs.getNullable(ItemDef::class.java, i)?.tradeable = t }
        TrouverLockables.registerAll()

        val rows = StringBuilder()
        rows.appendLine("# Death item audit (generated by DeathItemAuditTests, ${java.time.LocalDate.now()})")
        rows.appendLine()
        rows.appendLine("Owner rules 2026-10-04: lose everything, Protect Item keeps 1; lockable untradeables kept (lost only above level 20 when")
        rows.appendLine("not locked; always kept on a PvM death); every other untradeable always lost, the killer gets its High Alchemy value.")
        rows.appendLine()
        rows.appendLine("| id | item | group | PvP <=20 | PvP >20 | PvM | killer coins (<=20 / >20) |")
        rows.appendLine("|---|---|---|---|---|---|---|")
        val problems = mutableListOf<String>()
        var count = 0
        val ids = (tradeable.filterValues { !it }.keys + tradeable.keys.filter { PvpDeathBreakables.converts(it) }).toSortedSet()
        for (itemId in ids) {
            val def = defs.getNullable(ItemDef::class.java, itemId) ?: continue
            if (def.noted || itemId == Items.COINS_995) continue
            val name = names[itemId] ?: def.name
            if (name.isBlank() || name == "null") continue
            count++
            val item = Item(itemId, 1)
            val group: String
            val low: String
            val high: String
            val pvm: String
            var coins = ""
            when {
                DeathRules.alwaysLost(itemId) -> { group = "never kept (key/bag/emblem)"; low = "lost"; high = "lost"; pvm = "lost" }
                PvpDeathBreakables.converts(itemId) -> {
                    group = "converts"
                    val loot = PvpDeathBreakables.killerItems(item)
                    val shown = loot?.joinToString(" + ") { names[it.id] ?: defs.get(ItemDef::class.java, it.id).name } ?: "kept"
                    low = "killer gets $shown"; high = low; pvm = if (UntradeableDeathProtection.lockable(itemId)) "kept" else "gravestone"
                }
                UntradeableDeathProtection.handles(defs, itemId) -> {
                    val l = UntradeableDeathProtection.fateOf(defs, item, deepWilderness = false)
                    val h = UntradeableDeathProtection.fateOf(defs, item, deepWilderness = true)
                    group = if (UntradeableDeathProtection.lockable(itemId)) "lockable" + (if (TrouverRegistry.isLocked(itemId)) " (locked)" else "") else "untradeable"
                    low = l.fate.name.lowercase(); high = h.fate.name.lowercase()
                    pvm = if (UntradeableDeathProtection.lockable(itemId)) "kept" else "gravestone"
                    coins = "${l.killerCoins} / ${h.killerCoins}"
                    val keptAnyway = itemId in UntradeableDeathProtection.ALWAYS_KEPT_PVP || gg.rsmod.plugins.content.skills.summoning.Pets.isPetItem(itemId)
                    if (!keptAnyway && !UntradeableDeathProtection.lockable(itemId) && (l.fate != UntradeableFate.LOST_FOR_COINS || h.fate != UntradeableFate.LOST_FOR_COINS)) {
                        problems += "$itemId $name: a non-lockable untradeable must always be lost ($low / $high)"
                    }
                    if (UntradeableDeathProtection.lockable(itemId) && !UntradeableDeathProtection.isDamaged(item) && l.fate in setOf(UntradeableFate.DESTROYED, UntradeableFate.LOST_FOR_COINS)) {
                        problems += "$itemId $name: a lockable must be kept at <= 20 ($low)"
                    }
                }
                else -> { group = "untradeable (other rule)"; low = "lost"; high = "lost"; pvm = "gravestone" }
            }
            rows.appendLine("| $itemId | $name | $group | $low | $high | $pvm | $coins |")
        }
        File("../../../../docs/death-item-audit.md").also { it.parentFile.mkdirs() }.writeText(rows.toString())

        assertTrue(problems.isEmpty(), problems.joinToString("\n"))
        assertTrue(count > 100, "the audit really covers the item list ($count)")
        // Owner examples.
        val gloves = UntradeableDeathProtection.fateOf(defs, Item(Items.GLOVES_7462, 1), deepWilderness = false)
        assertEquals(UntradeableFate.LOST_FOR_COINS, gloves.fate, "Barrows gloves are always lost")
        assertTrue(gloves.killerCoins > 0, "the killer gets coins for them (${gloves.killerCoins})")
        assertEquals(UntradeableFate.POUCH_EMPTIED, UntradeableDeathProtection.fateOf(defs, Item(Items.RUNE_POUCH, 1), deepWilderness = false).fate)
        assertEquals(UntradeableFate.DESTROYED, UntradeableDeathProtection.fateOf(defs, Item(Items.RUNE_POUCH, 1), deepWilderness = true).fate)
        assertEquals(UntradeableFate.POUCH_EMPTIED, UntradeableDeathProtection.fateOf(defs, Item(Items.RUNE_POUCH_L, 1), deepWilderness = true).fate)
        assertEquals(UntradeableFate.MANGLED, UntradeableDeathProtection.fateOf(defs, Item(Items.INFERNAL_CAPE_L, 1), deepWilderness = true).fate)
        assertEquals(UntradeableFate.DESTROYED, UntradeableDeathProtection.fateOf(defs, Item(Items.INFERNAL_CAPE, 1), deepWilderness = true).fate)
        // Death audit 2026-10-04 (owner: OSRS conversions, max cape kept, untradeable flags).
        assertEquals(225_000L, UntradeableDeathProtection.fateOf(defs, Item(Items.COLOSSAL_BLADE, 1), false).killerCoins, "Colossal blade: 225,000 for the killer")
        assertEquals(78_000L, gloves.killerCoins, "Barrows gloves: 78,000")
        assertEquals(UntradeableFate.UNCHANGED, UntradeableDeathProtection.fateOf(defs, Item(Items.MAX_CAPE_20767, 1), true).fate, "max cape always kept")
        for (flipped in listOf(Items.DRAGON_DEFENDER, Items.MAX_CAPE_20767, Items.ELITE_VOID_KNIGHT_TOP, Items.FULL_SLAYER_HELMET)) {
            assertTrue(!defs.get(ItemDef::class.java, flipped).tradeable, "$flipped is untradeable like OSRS")
        }
        assertTrue(UntradeableDeathProtection.lockable(Items.ELITE_VOID_KNIGHT_TOP))
        // Owner 2026-10-06 ("your untradeable rule"): Arclight has no OSRS PvP rule - always lost, the killer gets its High Alchemy value.
        for (arclight in listOf(Items.ARCLIGHT, Items.ARCLIGHT_INACTIVE)) {
            assertTrue(!PvpDeathBreakables.converts(arclight) && UntradeableDeathProtection.handles(defs, arclight), "$arclight takes the untradeable route")
            for (deep in listOf(false, true)) {
                val fate = UntradeableDeathProtection.fateOf(defs, Item(arclight, 1), deep)
                assertEquals(UntradeableFate.LOST_FOR_COINS, fate.fate, "$arclight is lost")
                assertEquals(300L, fate.killerCoins, "$arclight: 300 coins (High Alchemy value in this cache)")
            }
        }
        assertEquals(listOf(Items.BLACK_MASK), PvpDeathBreakables.killerItems(Item(Items.FULL_SLAYER_HELMET, 1))?.map { it.id })
        assertEquals(listOf(Items.HELM_OF_NEITIZNOT, Items.BASILISK_JAW), PvpDeathBreakables.killerItems(Item(Items.NEITIZNOT_FACEGUARD, 1))?.map { it.id })
        assertEquals(listOf(Items.RING_OF_SUFFERING), PvpDeathBreakables.killerItems(Item(Items.RING_OF_SUFFERING_RI, 1))?.map { it.id })
        val venator = Item(Items.VENATOR_BOW, 1).also { it.attr[gg.rsmod.game.model.item.ItemAttribute.CHARGES] = 500 }
        assertEquals(listOf(Items.VENATOR_BOW_UNCHARGED to 1, Items.ANCIENT_ESSENCE to 500), PvpDeathBreakables.killerItems(venator)?.map { it.id to it.amount })
        // Every OSRS "(l)" list item this cache has is in the lockable group.
        for (osrs in listOf(Items.RUNE_POUCH, Items.DIVINE_RUNE_POUCH, Items.DIZANAS_QUIVER, Items.BLESSED_DIZANAS_QUIVER, Items.DIZANAS_MAX_CAPE,
            Items.INFERNAL_CAPE, Items.INFERNAL_MAX_CAPE, Items.VOID_KNIGHT_TOP, Items.VOID_KNIGHT_ROBE, Items.VOID_KNIGHT_GLOVES,
            Items.VOID_MAGE_HELM, Items.VOID_RANGER_HELM, Items.VOID_MELEE_HELM, Items.FIGHTER_TORSO, Items.ANCIENT_SCEPTRE)) {
            assertTrue(UntradeableDeathProtection.lockable(osrs), "$osrs is on the OSRS (l) list")
        }
    }
}
