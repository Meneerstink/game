    /** The frame durations of a rev-667 sequence, whether it already has frame sounds (opcode 13), and the offset of its end byte. */
    class Seq667(val durations: IntArray, val hasSounds: Boolean, val end: Int)

    fun read667Seq(bytes: ByteArray): Seq667 {
        val c = OsrsFxImportTool.Cursor(bytes)
        var durations = IntArray(0)
        var sounds = false
        while (true) {
            val at = c.pos
            when (val op = c.u8()) {
                0 -> {
                    check(c.pos == bytes.size) { "sequence has trailing bytes" }
                    return Seq667(durations, sounds, at)
                }
                1 -> {
                    val n = c.u16()
                    durations = IntArray(n) { c.u16() }
                    repeat(n * 2) { c.u16() }
                }
                2 -> c.u16()
                3 -> repeat(c.u8()) { c.u8() }
                5, 8, 9, 10, 11 -> c.u8()
                6, 7 -> c.u16()
                12 -> repeat(c.u8() * 2) { c.u16() }
                13 -> {
                    sounds = true
                    repeat(c.u16()) {
                        val options = c.u8()
                        if (options > 0) {
                            c.u8()
                            c.u16()
                            repeat(options - 1) { c.u16() }
                        }
                    }
                }
                14, 15, 16, 18 -> Unit
                else -> error("opcode $op is not a 667 sequence opcode")
            }
        }
    }

    /** [bytes] with a frame-sound block (frame -> packed `synth << 8 | loops << 5 | radius`) put before its end byte. */
    fun with667Sounds(
        bytes: ByteArray,
        seq: Seq667,
        packed: Map<Int, Int>,
    ): ByteArray {
        val out = java.io.ByteArrayOutputStream()
        out.write(bytes, 0, seq.end)
        out.write(13)
        out.write(seq.durations.size ushr 8)
        out.write(seq.durations.size and 0xFF)
        for (frame in seq.durations.indices) {
            val p = packed[frame]
            if (p == null) {
                out.write(0)
            } else {
                out.write(1)
                out.write(p ushr 16)
                out.write((p ushr 8) and 0xFF)
                out.write(p and 0xFF)
            }
        }
        out.write(0)
        return out.toByteArray()
    }

    /**
     * Where the lent sounds land: each source sound at the same fraction of the target cycle ([time] of [sourceLength] client cycles ->
     * the target frame showing that moment); two on one frame -> the later moves to the next free frame, none past the last frame.
     */
    fun lentFrames(
        events: List<IntArray>,
        sourceLength: Int,
        targetDurations: IntArray,
    ): List<Pair<IntArray, Int>> {
        val starts = IntArray(targetDurations.size)
        for (i in 1 until starts.size) starts[i] = starts[i - 1] + targetDurations[i - 1]
        val targetLength = targetDurations.sum().toLong()
        val used = mutableSetOf<Int>()
        val out = mutableListOf<Pair<IntArray, Int>>()
        for (e in events.sortedBy { it[0] }) {
            if (e[2] < 1) continue
            val at = e[0] * targetLength / sourceLength.coerceAtLeast(1)
            var frame = starts.indexOfLast { it <= at }.coerceAtLeast(0)
            while (frame in used) frame++
            if (frame >= starts.size) continue
            used += frame
            out += e to frame
        }
        return out
    }

    /** OSRS sounds of one sequence as [time, synth, loops, radius] plus the cycle length, both in client cycles. */
    fun osrsSeqSounds(
        reader: ModernCacheReader,
        osrsSeq: Int,
    ): Pair<List<IntArray>, Int> {
        val bytes = reader.file(ModernCacheReader.INDEX_CONFIG, ModernCacheReader.CONFIG_GROUP_SEQUENCE, osrsSeq) ?: error("OSRS sequence $osrsSeq missing")
        val skeletal = SkeletalBakeTool.decodeSkeletalSeq(bytes)
        if (skeletal != null) {
            // One skeletal tick per client cycle ([SkeletalBakeTool.bakeSet]); the range is the sequence's own, else the whole clip.
            val range =
                if (skeletal.start >= 0 && skeletal.end > skeletal.start) {
                    skeletal.start until skeletal.end
                } else {
                    val clip = SkeletalBakeTool.decodeClip(reader.file(SkeletalBakeTool.INDEX_ANIMAYA, skeletal.animaya ushr 16, skeletal.animaya and 0xFFFF)!!)
                    0..clip.lastTick
                }
            return skeletal.sounds.map { (tick, synth, loops, radius) -> intArrayOf(tick - range.first, synth, loops, radius) } to (range.last - range.first + 1)
        }
        val seq = OsrsFxImportTool.decodeOsrsSeq(bytes)
        val starts = IntArray(seq.frameDurations.size)
        for (i in 1 until starts.size) starts[i] = starts[i - 1] + seq.frameDurations[i - 1]
        return seq.soundList.map { (frame, synth, loops, radius) -> intArrayOf(starts.getOrElse(frame) { seq.frameDurations.sum() }, synth, loops, radius) } to seq.frameDurations.sum()
    }

    private fun sounds(apply: Boolean) {
        val rows = OsrsPetRoster.load().associateBy { it.osrsFollower }
        val assetMap = File(OsrsItemImportTool.ASSET_MAP)
        val targets = OsrsItemImportTool.TARGETS
        val reader = ModernCacheReader(File(OsrsItemImportTool.SOURCE_CACHE))
        val library = CacheLibrary(targets[0])
        val mutations = mutableListOf<CacheMutation>()
        val records = mutableListOf<String>()
        val plans = mutableListOf<String>()
        try {
            var nextSynth = (library.index(OsrsFxImportTool.INDEX_SYNTH).archiveIds().maxOrNull() ?: -1) + 1
            val localIds = OsrsFxImportTool.existingFx(assetMap).toMutableMap()
            fun local(kind: String, upstream: Int, allocate: () -> Int): Int =
                localIds.getOrPut("$kind:$upstream") { allocate().also { records += "$kind|$upstream|$it" } }
            val npcFiles = reader.files(ModernCacheReader.INDEX_CONFIG, OsrsNpcProbeTool.CONFIG_GROUP_NPC)
            val done = mutableSetOf<Int>()
            for ((targetNpc, sourceNpc) in LENT_SOUNDS) {
                val row = rows[targetNpc] ?: error("$targetNpc is no roster follower")
                val target = OsrsNpcProbeTool.decodeOsrs(targetNpc, npcFiles.getValue(targetNpc))
                val source = OsrsNpcProbeTool.decodeOsrs(sourceNpc, npcFiles.getValue(sourceNpc))
                check(target.follower && !source.follower) { "${row.variant}: $targetNpc must be the follower and $sourceNpc not" }
                val targetSeqs = OsrsNpcProbeTool.movementSeqs(target)
                val baked = if (row.skeletal) bakedSeqs(target) else emptyList()
                // Walks first: where the pet stands and walks with one sequence (Quetzin), it gets the walk's sounds.
                for ((move, sourceSeq) in OsrsNpcProbeTool.movementSeqs(source).entries.sortedBy { it.key == "stand" }) {
                    val targetSeq = targetSeqs[move] ?: continue
                    val (events, sourceLength) = osrsSeqSounds(reader, sourceSeq)
                    if (events.isEmpty()) continue
                    val key = if (row.skeletal) "pet_baked_seq:${packed(targetNpc, baked.indexOf(targetSeq))}" else "seq:$targetSeq"
                    val localSeq = localIds[key] ?: error("${row.variant}: $key not imported")
                    if (!done.add(localSeq)) continue // stand = walk, or a sequence two variants share: once
                    val bytes = library.data(OsrsFxImportTool.INDEX_SEQ, localSeq ushr 7, localSeq and 0x7F) ?: error("local seq $localSeq missing")
                    val seq = read667Seq(bytes)
                    if (seq.hasSounds) {
                        plans += "KEEP ${row.variant} $move local seq $localSeq already has frame sounds"
                        continue
                    }
                    val packedSounds = sortedMapOf<Int, Int>()
                    val mapped = mutableListOf<String>()
                    for ((e, frame) in lentFrames(events, sourceLength, seq.durations)) {
                        val (time, synth, loops, radius) = e
                        val localSynth =
                            local("synth", synth) { nextSynth++ }.also { id ->
                                if (library.data(OsrsFxImportTool.INDEX_SYNTH, id, 0) == null) {
                                    val data = reader.file(OsrsFxImportTool.INDEX_SYNTH, synth, 0) ?: error("OSRS synth $synth missing")
                                    mutations += CacheMutation(OsrsFxImportTool.INDEX_SYNTH, id, 0, data, "osrs synth $synth")
                                }
                            }
                        packedSounds[frame] = (localSynth shl 8) or (loops.coerceAtMost(7) shl 5) or OsrsFxImportTool.packedRadius(radius)
                        mapped += "$synth->$localSynth t$time/$sourceLength->f$frame/${seq.durations.size} r$radius"
                    }
                    val out = with667Sounds(bytes, seq, packedSounds)
                    OsrsFxImportTool.decode667SeqFrames(out)
                    mutations +=
                        CacheMutation(
                            OsrsFxImportTool.INDEX_SEQ, localSeq ushr 7, localSeq and 0x7F, out,
                            "N88 ${row.variant} $move: sounds of osrs npc $sourceNpc seq $sourceSeq",
                            expectedCurrentSha1 = CacheItemProbeTool.sha1(bytes),
                        )
                    plans += "PLAN ${row.variant} ($targetNpc) $move local seq $localSeq <- ${source.name} ($sourceNpc) seq $sourceSeq: ${mapped.joinToString(", ")}"
                }
            }
        } finally {
            library.close()
            reader.close()
        }
        plans.forEach { println(it) }
        val unique = mutations.distinctBy { it.describeLocation() }
        val transaction = CacheTransaction(targets = targets, mutations = unique)
        val plan = transaction.preflight()
        val errors = transaction.blockingErrors(plan)
        println("PREFLIGHT transaction=${transaction.id} mutations=${unique.size} outcomes=${plan.groupingBy { it.outcome }.eachCount()}")
        errors.forEach { println("  BLOCKING: $it") }
        check(errors.isEmpty()) { "preflight blocked; nothing written" }
        if (!apply) {
            println("DRY_RUN records=${records.size}")
            return
        }
        val result = transaction.apply(plan)
        val problems = transaction.verify()
        if (problems.isNotEmpty()) {
            problems.forEach { println("  VERIFY_FAILURE: $it") }
            println("ROLLED_BACK ${transaction.rollback()}")
            error("transaction ${transaction.id} failed verification and was rolled back")
        }
        println("APPLIED transaction=${result.transactionId} writes=${result.applied} skipped=${result.skipped}")
        if (records.isNotEmpty()) {
            val block = StringBuilder()
            records.forEach { r ->
                val (kind, upstream, localId) = r.split('|')
                block.append("  - fx_kind: $kind\n    upstream_fx_id: $upstream\n    local_fx_id: $localId\n    status: IMPORTED_BY_OSRS_PET_TOOL\n    transaction: ${transaction.id}\n")
            }
            val text = assetMap.readText()
            assetMap.writeText(if (text.endsWith("\n")) text + block else "$text\n$block")
            println("ASSET_MAP appended ${records.size} pet import entries")
        }
    }

    /** Writes [OsrsPetRoster.SERVER_TABLE]; every roster row must have both its item and its follower npc imported. */
    private fun table() {
        val assetMap = File(OsrsItemImportTool.ASSET_MAP)
        val items = OsrsFxImportTool.importedItems(assetMap)
        val fx = OsrsFxImportTool.existingFx(assetMap)
        val rows = OsrsPetRoster.load()
        val missing = rows.filter { items[it.osrsItem] == null || fx["npc:${it.osrsFollower}"] == null }
        check(missing.isEmpty()) { "not imported yet: ${missing.map { "${it.variant} item=${it.osrsItem}:${items[it.osrsItem]} npc=${it.osrsFollower}:${fx["npc:${it.osrsFollower}"]}" }}" }
        val out = StringBuilder()
        out.append("# Generated by OsrsPetImportTool table from OSRS_IMPORT_MASTER.yml - do not edit; the source is osrs_pets.tsv.\n")
        out.append("# pet\tvariant\titem\tnpc\tosrs_item\tosrs_npc\n")
        rows.forEach { r -> out.append("${r.pet}\t${r.variant}\t${items.getValue(r.osrsItem)}\t${fx.getValue("npc:${r.osrsFollower}")}\t${r.osrsItem}\t${r.osrsFollower}\n") }
        File(OsrsPetRoster.SERVER_TABLE).writeText(out.toString())
        println("TABLE_WRITTEN ${OsrsPetRoster.SERVER_TABLE} rows=${rows.size}")

        // Emotes: skeletal followers' sequences are the baked ones (asset key pet_baked_seq, packed by their [bakedSeqs] position),
        // classic ones the imported OSRS sequences (asset key seq); the spotanim is OsrsFxImportTool's.
        val emotes = StringBuilder()
        emotes.append("# Generated by OsrsPetImportTool table from OSRS_IMPORT_MASTER.yml - do not edit; the source is OsrsPetImportTool.EMOTES.\n")
        emotes.append("# npc\temote\tseqs\tspotanim\tosrs_npc\tosrs_seqs\n")
        var emoteRows = 0
        ModernCacheReader(File(OsrsItemImportTool.SOURCE_CACHE)).use { reader ->
            val npcFiles = reader.files(ModernCacheReader.INDEX_CONFIG, OsrsNpcProbeTool.CONFIG_GROUP_NPC)
            for ((osrsNpc, list) in EMOTES) {
                val row = rows.firstOrNull { it.osrsFollower == osrsNpc } ?: error("emote npc $osrsNpc is no roster follower")
                val localNpc = fx.getValue("npc:$osrsNpc")
                val baked = if (row.skeletal) bakedSeqs(OsrsNpcProbeTool.decodeOsrs(osrsNpc, npcFiles.getValue(osrsNpc))) else emptyList()
                for (e in list) {
                    val seqs =
                        e.osrsSeqs.map { s ->
                            val key = if (row.skeletal) "pet_baked_seq:${packed(osrsNpc, baked.indexOf(s))}" else "seq:$s"
                            fx[key] ?: error("emote ${row.variant} ${e.name}: $key not imported")
                        }
                    val spot = if (e.osrsSpot >= 0) fx["spotanim:${e.osrsSpot}"] ?: error("emote ${row.variant} ${e.name}: spotanim ${e.osrsSpot} not imported") else -1
                    emotes.append("$localNpc\t${e.name}\t${seqs.joinToString(",")}\t$spot\t$osrsNpc\t${e.osrsSeqs.joinToString(",")}\n")
                    emoteRows++
                }
            }
        }
        File(EMOTE_TABLE).writeText(emotes.toString())
        println("TABLE_WRITTEN $EMOTE_TABLE rows=$emoteRows")
    }

    @JvmStatic
    fun main(args: Array<String>) {
        val rows = OsrsPetRoster.load()
        when (args.firstOrNull()) {
            "skeletal" -> skeletal("--apply" in args)
            "sounds" -> sounds("--apply" in args)
            "table" -> table()
            "probe" ->
                ModernCacheReader(File(OsrsItemImportTool.SOURCE_CACHE)).use { reader ->
                    val npcFiles = reader.files(ModernCacheReader.INDEX_CONFIG, OsrsNpcProbeTool.CONFIG_GROUP_NPC)
                    val itemFiles = reader.files(ModernCacheReader.INDEX_CONFIG, ModernCacheReader.CONFIG_GROUP_ITEM)
                    val seqFiles = reader.files(ModernCacheReader.INDEX_CONFIG, ModernCacheReader.CONFIG_GROUP_SEQUENCE)
                    var skeletalRows = 0
                    var refused = 0
                    for (row in rows) {
                        val item = itemFiles[row.osrsItem]?.let { ModernItemDefDecoder.decode(row.osrsItem, it) }
                        val npc = followerNpc(row, npcFiles)
                        if (item == null || npc == null) {
                            refused++
                            println("PET '${row.pet}' / '${row.variant}' item=${row.osrsItem}${if (item == null) " ABSENT" else ""} npcs=${row.osrsNpcs} FOLLOWER_ABSENT=${npc == null}")
                            continue
                        }
                        val seqs = OsrsNpcProbeTool.movementSeqs(npc).values.distinct()
                        val skeletal = seqs.filter { s -> seqFiles[s]?.let { SkeletalBakeTool.decodeSkeletalSeq(it) } != null }
                        val models =
                            npc.models.map { m ->
                                val raw = ModernModelDecoder.decode(reader.file(7, m, 0) ?: error("model $m missing"), flattenTextures = true)
                                "$m:v${raw.vertexCount}${if (raw.animayaBones != null) ":skin${clusters(raw)}" else ""}"
                            }
                        if (skeletal.isNotEmpty()) skeletalRows++
                        println(
                            "PET '${row.pet}' / '${row.variant}' item ${row.osrsItem} '${item.name}' iops=${item.inventoryOptions.toList()} " +
                                "npc ${npc.id} '${npc.name}' size=${npc.size} ops=${npc.ops.toList()} models=$models heads=${npc.chatheads.toList()} " +
                                "seqs=$seqs skeletal=$skeletal scale=${npc.widthScale}x${npc.heightScale}",
                        )
                    }
                    println("SUMMARY rows=${rows.size} refused=$refused skeletal_rows=$skeletalRows")
                }
            else -> error("Usage: probe | skeletal [--apply] | sounds [--apply] | table")
        }
    }
